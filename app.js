function answerPlayerQuestion(player, question) {
  var q = normalize(question);
  if (!q) return '—';

  // اسم
  for (var i = 0; i < PLAYERS.length; i++) {
    var p = PLAYERS[i];
    if (q.indexOf(normalize(p.name)) >= 0) {
      return p.name === player.name ? 'نعم' : 'لا';
    }
  }

  // جنسية
  for (var j = 0; j < PLAYERS.length; j++) {
    if (q.indexOf(normalize(PLAYERS[j].nat)) >= 0) {
      return player.nat === PLAYERS[j].nat ? 'نعم' : 'لا';
    }
  }

  // مركز
  var positions = ['حارس مرمى', 'مدافع', 'وسط', 'مهاجم', 'حارس'];
  for (var k = 0; k < positions.length; k++) {
    if (q.indexOf(normalize(positions[k])) >= 0) {
      return player.pos.indexOf(positions[k]) >= 0 ? 'نعم' : 'لا';
    }
  }

  // نادي
  for (var m = 0; m < ALL_CLUBS.length; m++) {
    if (q.indexOf(normalize(ALL_CLUBS[m])) >= 0) {
      for (var n = 0; n < player.clubs.length; n++) {
        if (normalize(player.clubs[n]) === normalize(ALL_CLUBS[m])) return 'نعم';
      }
      return 'لا';
    }
  }

  // بطولة
  var comps = ['كأس العالم','دوري أبطال أوروبا','كأس الأمم الأفريقية','اليورو الأوروبي','الدوري الإنجليزي','الدوري الإسباني','الدوري الإيطالي','الدوري الألماني','الدوري الفرنسي'];
  for (var c = 0; c < comps.length; c++) {
    if (q.indexOf(normalize(comps[c])) >= 0) {
      for (var x = 0; x < player.comps.length; x++) {
        if (normalize(player.comps[x]) === normalize(comps[c])) return 'نعم';
      }
      return 'لا';
    }
  }

  return 'لا أعرف 🤔';
}

