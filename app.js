function getCorrectPlayersForCondition(condition) {
  var c = normalize(condition);
  var result = [];
  var isLabaFi = c.indexOf('لعب في') === 0;
  var isFazBi = c.indexOf('فاز ب') === 0;
  var target = '';
  if (isLabaFi) target = normalize(condition.replace('لعب في', '').trim());
  else if (isFazBi) target = normalize(condition.replace(/فاز ب[ـ]?/, '').trim());
  else return result;

  for (var i = 0; i < PLAYERS.length; i++) {
    var p = PLAYERS[i];
    if (isLabaFi) {
      // دوري؟
      var matched = false;
      for (var league in CLUBS_BY_LEAGUE) {
        var nLeague = normalize(league);
        if (nLeague.indexOf(target) >= 0 || target.indexOf(nLeague) >= 0) {
          for (var x = 0; x < p.comps.length; x++) {
            if (normalize(p.comps[x]).indexOf(target) >= 0) { matched = true; break; }
          }
          if (!matched) {
            var clubs = CLUBS_BY_LEAGUE[league];
            for (var y = 0; y < p.clubs.length && !matched; y++) {
              for (var z = 0; z < clubs.length; z++) {
                if (normalize(clubs[z]) === normalize(p.clubs[y])) { matched = true; break; }
              }
            }
          }
          if (matched) break;
        }
      }
      if (!matched) {
        for (var k = 0; k < p.clubs.length; k++) {
          if (normalize(p.clubs[k]).indexOf(target) >= 0) { matched = true; break; }
        }
      }
      if (matched) result.push(p.name);
    } else {
      for (var m = 0; m < p.comps.length; m++) {
        if (normalize(p.comps[m]).indexOf(target) >= 0) { result.push(p.name); break; }
      }
    }
  }
  return result;
}

