var ONLINE = { active: false, channel: null, opponent: null };

function sendChallenge(friendId, friendName) {
  if (!sb || STATE.guest) { toast('سجّل دخول للعب أونلاين'); return; }

  var choice = window.prompt('اختر نوع المباراة:\n1) أسئلة كروية\n2) كوّن تشكيلتك\n\nاكتب 1 أو 2');
  var mode = null;
  if (choice === '1') mode = 'quiz';
  else if (choice === '2') mode = 'squad';
  if (!mode) return;

  sb.from('challenge_requests').insert({
    from_id: STATE.user.id,
    from_name: STATE.user.username,
    to_id: friendId,
    mode: mode,
    status: 'pending'
  }).then(function(res) {
    if (res.error) throw res.error;
    toast('تم إرسال التحدي إلى ' + friendName, true);
  }).catch(function(err) {
    console.error(err);
    toast('خطأ في إرسال التحدي');
  });
}

function listenForChallenges() {
  if (!sb || STATE.guest || !STATE.user || STATE.user.id === 'guest') return;
  if (ONLINE.channel) return;

  try {
    ONLINE.channel = sb.channel('challenges-' + STATE.user.id)
      .on('postgres_changes', {
        event: 'INSERT',
        schema: 'public',
        table: 'challenge_requests',
        filter: 'to_id=eq.' + STATE.user.id
      }, function(payload) { handleIncomingChallenge(payload.new); })
      .subscribe();
    console.log('[Online] listening');
  } catch (e) { console.warn('realtime failed', e); }
}

function handleIncomingChallenge(req) {
  var wrap = $('#incoming-requests');
  if (!wrap) return;

  var row = document.createElement('div');
  row.className = 'friend-row';
  var letter = (req.from_name || '?').charAt(0);
  row.innerHTML =
    '<div class="avatar" style="background:#d4af37">' + letter + '</div>' +
    '<div class="name">' + req.from_name + '<br><small style="color:#888;font-size:11px">' +
      (req.mode === 'quiz' ? 'أسئلة كروية' : 'كوّن تشكيلتك') + '</small></div>' +
    '<button class="btn-primary" data-accept="' + req.id + '">قبول</button>' +
    '<button class="btn-ghost" data-reject="' + req.id + '">رفض</button>';

  row.querySelector('[data-accept]').addEventListener('click', function() { acceptChallenge(req); });
  row.querySelector('[data-reject]').addEventListener('click', function() { rejectChallenge(req); });
  wrap.appendChild(row);

  toast('📩 ' + req.from_name + ' أرسل لك تحدي!', true);
}

function acceptChallenge(req) {
  if (!sb) return;
  sb.from('challenge_requests').update({ status: 'accepted' }).eq('id', req.id).then(function() {
    toast('تم القبول — جاري بدء المباراة...', true);
    AI.currentBot = { name: req.from_name, avatar: '' };
    STATE.currentMode = req.mode;
    setTimeout(function() {
      if (req.mode === 'quiz') startQuizGame();
      else startSquadGame();
    }, 1200);
  }).catch(function(err) { console.error(err); });
}

function rejectChallenge(req) {
  if (!sb) return;
  sb.from('challenge_requests').update({ status: 'rejected' }).eq('id', req.id).then(function() {
    toast('تم الرفض');
  }).catch(function(err) { console.error(err); });
}

