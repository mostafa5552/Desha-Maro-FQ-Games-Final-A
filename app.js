function initSplash() {
  console.log('[Splash] init');
  showScreen('splash-screen', false);
  SCREEN_STACK.length = 0;
  SCREEN_STACK.push('splash-screen');

  var navigated = false;
  function goAuth() {
    if (navigated) return;
    navigated = true;
    console.log('[Splash] → auth');
    showScreen('auth-screen', false);
  }

  var safetyTimer = setTimeout(function() {
    console.warn('[Splash] safety timeout');
    goAuth();
  }, 3000);

  (function() {
    try {
      if (!sb) { clearTimeout(safetyTimer); goAuth(); return; }

      var done = false;
      var timeoutCheck = setTimeout(function() {
        if (done) return;
        done = true;
        console.warn('[Splash] getSession timeout');
        clearTimeout(safetyTimer);
        goAuth();
      }, 1800);

      sb.auth.getSession().then(function(res) {
        if (done) return;
        done = true;
        clearTimeout(timeoutCheck);
        clearTimeout(safetyTimer);
        var session = res && res.data ? res.data.session : null;
        if (session && session.user) {
          loadProfileAndEnter(session.user).catch(function(err) {
            console.error('[Splash] loadProfile failed', err);
            goAuth();
          });
        } else {
          goAuth();
        }
      }).catch(function(err) {
        if (done) return;
        done = true;
        clearTimeout(timeoutCheck);
        clearTimeout(safetyTimer);
        console.error('[Splash] getSession error', err);
        goAuth();
      });
    } catch (e) {
      console.error('[Splash] catch', e);
      clearTimeout(safetyTimer);
      goAuth();
    }
  })();
}

