function rnd(arr) { return arr[Math.floor(Math.random() * arr.length)]; }
function rndInt(min, max) { return Math.floor(Math.random() * (max - min + 1)) + min; }
function shuffle(a) { var b = a.slice(); for (var i = b.length - 1; i > 0; i--) { var j = rndInt(0, i); var t = b[i]; b[i] = b[j]; b[j] = t; } return b; }

function normalize(str) {
  if (!str) return '';
  return String(str).trim().toLowerCase()
    .replace(/[\u064B-\u065F\u0670]/g, '')
    .replace(/[أإآٱ]/g, 'ا')
    .replace(/ى/g, 'ي')
    .replace(/ؤ/g, 'و')
    .replace(/ئ/g, 'ي')
    .replace(/ة/g, 'ه')
    .replace(/[^\u0600-\u06FFa-z0-9\s]/g, '')
    .replace(/\s+/g, ' ')
    .trim();
}

function isNameMatch(userAnswer, correctName, aliases) {
  aliases = aliases || [];
  var u = normalize(userAnswer);
  if (!u) return false;
  var candidates = [correctName].concat(aliases).map(normalize);
  for (var i = 0; i < candidates.length; i++) {
    var c = candidates[i];
    if (!c) continue;
    if (u === c) return true;
    var parts = c.split(' ').filter(function(p) { return p.length > 2; });
    for (var j = 0; j < parts.length; j++) { if (u === parts[j]) return true; }
    if (u.length >= 4 && (c.indexOf(u) >= 0 || u.indexOf(c) >= 0)) return true;
  }
  return false;
}

