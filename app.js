/* ============ قوة الفريق ============ */
function calculateTeamStrength(squad) {
  var strength = 0;
  var count = 0;
  var keys = Object.keys(squad);
  for (var i = 0; i < keys.length; i++) {
    var p = squad[keys[i]];
    if (!p) continue;
    var idx = -1;
    for (var j = 0; j < PLAYERS.length; j++) {
      if (PLAYERS[j].name === p.name) { idx = j; break; }
    }
    var fame = idx >= 0 ? Math.max(0.3, 1 - idx / PLAYERS.length) : 0.5;
    strength += 30 + fame * 70;
    count++;
  }
  return count > 0 ? strength / count : 50;
}

/* ============ المحاكاة العرضية ============ */
var SIM = { myScore: 0, oppScore: 0, timer: 60, loopId: null, tickId: null, myDots: [], oppDots: [] };

function startSimulation() {
  SIM.myScore = 0;
  SIM.oppScore = 0;
  SIM.timer = 60;

  var myStrength = calculateTeamStrength(SQUAD.mySquad);
  var oppStrength = calculateTeamStrength(SQUAD.oppSquad);
  var diff = myStrength - oppStrength;

  showScreen('simulation-screen');
  var scoreMe = $('#sim-my-score'); if (scoreMe) scoreMe.textContent = '0';
  var scoreOpp = $('#sim-opp-score'); if (scoreOpp) scoreOpp.textContent = '0';
  var timerEl = $('#sim-timer'); if (timerEl) timerEl.textContent = '60';

  var field = $('#sim-field');
  if (!field) return;
  field.innerHTML = '';

  var keys = SQUAD_POSITIONS.map(function(p) { return p.key; });
  SIM.myDots = [];
  SIM.oppDots = [];

  for (var i = 0; i < keys.length; i++) {
    var el = document.createElement('div');
    el.className = 'dot me';
    var myP = SQUAD.mySquad[keys[i]];
    el.textContent = (myP && myP.name ? myP.name.charAt(0) : '?');
    field.appendChild(el);
    SIM.myDots.push(el);
  }
  for (var j = 0; j < keys.length; j++) {
    var el2 = document.createElement('div');
    el2.className = 'dot opp';
    var opP = SQUAD.oppSquad[keys[j]];
    el2.textContent = (opP && opP.name ? opP.name.charAt(0) : '?');
    field.appendChild(el2);
    SIM.oppDots.push(el2);
  }

  positionDots();

  if (SIM.tickId) clearInterval(SIM.tickId);
  SIM.tickId = setInterval(function() {
    SIM.timer--;
    var t = $('#sim-timer'); if (t) t.textContent = SIM.timer;
    if (SIM.timer <= 0) {
      clearInterval(SIM.tickId);
      SIM.tickId = null;
      endSimulation(diff);
    }
  }, 1000);

  simulateLoop(diff);
}

function positionDots() {
  var field = $('#sim-field');
  if (!field) return;
  var w = field.clientWidth || 300;
  var h = field.clientHeight || 450;
  for (var i = 0; i < SIM.myDots.length; i++) {
    SIM.myDots[i].style.left = (w * 0.2 + (i % 2) * w * 0.15) + 'px';
    SIM.myDots[i].style.top = (h * 0.1 + i * h * 0.18) + 'px';
  }
  for (var j = 0; j < SIM.oppDots.length; j++) {
    SIM.oppDots[j].style.left = (w * 0.65 - (j % 2) * w * 0.15) + 'px';
    SIM.oppDots[j].style.top = (h * 0.1 + j * h * 0.18) + 'px';
  }
}

function moveDots() {
  var field = $('#sim-field');
  if (!field) return;
  var w = field.clientWidth || 300;
  var h = field.clientHeight || 450;
  var all = SIM.myDots.concat(SIM.oppDots);
  for (var i = 0; i < all.length; i++) {
    all[i].style.left = (w * 0.1 + Math.random() * w * 0.7) + 'px';
    all[i].style.top = (h * 0.05 + Math.random() * h * 0.85) + 'px';
  }
}

function simulateLoop(diff) {
  if (SIM.timer <= 0) return;
  SIM.tickId && setTimeout(function() {
    if (SIM.timer <= 0) return;
    moveDots();

    var myChance = 0.35 + diff * 0.005;
    var oppChance = 0.35 - diff * 0.005;
    if (myChance < 0.15) myChance = 0.15;
    if (myChance > 0.7) myChance = 0.7;
    if (oppChance < 0.15) oppChance = 0.15;
    if (oppChance > 0.7) oppChance = 0.7;

    var r = Math.random();
    if (r < myChance) {
      SIM.myScore++;
      var elMe = $('#sim-my-score'); if (elMe) elMe.textContent = SIM.myScore;
      vibrate(40);
      flashField('#d32f2f');
    } else if (r > 1 - oppChance) {
      SIM.oppScore++;
      var elOpp = $('#sim-opp-score'); if (elOpp) elOpp.textContent = SIM.oppScore;
      flashField('#ffffff');
    }

    if (SIM.timer > 0) simulateLoop(diff);
  }, 2500);
}

function flashField(color) {
  var field = $('#sim-field');
  if (!field) return;
  var old = field.style.boxShadow;
  field.style.boxShadow = '0 0 40px ' + color;
  setTimeout(function() { field.style.boxShadow = old; }, 400);
}

function endSimulation(diff) {
  if (SIM.myScore === SIM.oppScore) setTimeout(penaltyShootout, 800);
  else {
    var win = SIM.myScore > SIM.oppScore;
    setTimeout(function() { showSquadResult(win, SIM.myScore, SIM.oppScore); }, 800);
  }
}

/* ============ ضربات الترجيح ============ */
function penaltyShootout() {
  toast('⚽ ضربات ترجيح!', true);
  var me = 0, opp = 0;
  var prof = AI.getProfile();
  var myRate = 0.75;
  var oppRate = 0.55 + prof.accuracy * 0.3;

  for (var i = 0; i < 5; i++) {
    if (Math.random() < myRate) me++;
    if (Math.random() < oppRate) opp++;
  }
  var safety = 0;
  while (me === opp && safety < 20) {
    if (Math.random() < myRate) me++;
    if (Math.random() < oppRate) opp++;
    safety++;
  }
  if (me === opp) me++; // fallback

  var win = me > opp;
  setTimeout(function() {
    var elMe = $('#sim-my-score'); if (elMe) elMe.textContent = SIM.myScore + ' (+' + me + ')';
    var elOpp = $('#sim-opp-score'); if (elOpp) elOpp.textContent = SIM.oppScore + ' (+' + opp + ')';
    setTimeout(function() { showSquadResult(win, SIM.myScore + me, SIM.oppScore + opp); }, 1500);
  }, 500);
}

