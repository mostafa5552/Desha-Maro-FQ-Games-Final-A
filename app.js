function updateDivisionList() {
  var wrap = $('#divisions-list');
  if (!wrap) return;

  var currentDiv = (STATE.profile && STATE.profile.current_division) || 1;
  var progress = (STATE.profile && STATE.profile.division_progress) || 0;

  wrap.innerHTML = '';
  for (var i = 0; i < DIVISIONS.length; i++) {
    (function(div) {
      var isUnlocked = div.id <= currentDiv;
      var isCurrent = div.id === currentDiv;
      var divEl = document.createElement('div');
      divEl.className = 'division-card';
      if (!isUnlocked) divEl.classList.add('locked');
      if (isCurrent) divEl.classList.add('current');

      var progPct = isCurrent ? Math.min(100, (progress / div.matches) * 100) : (isUnlocked ? 100 : 0);

      divEl.innerHTML =
        '<div class="div-badge">' + div.icon + '</div>' +
        '<div class="div-info">' +
          '<h3>دفيجن ' + div.id + ' — ' + div.name + '</h3>' +
          '<p>' + (isUnlocked ? div.desc : '🔒 أكمل الدفيجن السابق') + '</p>' +
          '<div class="div-progress"><span style="width:' + progPct + '%"></span></div>' +
          '<p style="margin-top:4px;font-size:11px;color:#d4af37">' +
            (isCurrent ? (progress + ' / ' + div.matches + ' مباراة') : (isUnlocked ? '✅ مكتمل' : '')) +
          '</p>' +
        '</div>';

      if (isUnlocked) {
        divEl.addEventListener('click', function() { openDivision(div.id); });
      }
      wrap.appendChild(divEl);
    })(DIVISIONS[i]);
  }
}

