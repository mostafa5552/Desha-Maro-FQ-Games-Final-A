var SCREEN_STACK = [];
var PENDING_NAV_TIMEOUT = null;

function showScreen(id, push) {
  if (push === undefined) push = true;
  var current = document.querySelector('.screen.active');
  if (current && current.id === id) return;

  if (PENDING_NAV_TIMEOUT) {
    clearTimeout(PENDING_NAV_TIMEOUT);
    PENDING_NAV_TIMEOUT = null;
  }

  var all = $$('.screen');
  for (var i = 0; i < all.length; i++) all[i].classList.remove('active');

  var next = document.getElementById(id);
  if (!next) { console.warn('Screen not found:', id); return; }
  next.classList.add('active');
  next.scrollTop = 0;

  if (push) {
    var idx = SCREEN_STACK.lastIndexOf(id);
    if (idx >= 0) SCREEN_STACK.length = idx + 1;
    else SCREEN_STACK.push(id);
  } else {
    SCREEN_STACK.length = 0;
    SCREEN_STACK.push(id);
  }
}

function goBack() {
  if (PENDING_NAV_TIMEOUT) {
    clearTimeout(PENDING_NAV_TIMEOUT);
    PENDING_NAV_TIMEOUT = null;
  }
  try {
    if (typeof AI !== 'undefined' && AI && typeof AI.clear === 'function') AI.clear();
    if (typeof clearQuizTimers === 'function') clearQuizTimers();
    if (typeof clearSquadTimers === 'function') clearSquadTimers();
  } catch (e) {}

  if (SCREEN_STACK.length <= 1) {
    SCREEN_STACK.length = 0;
    SCREEN_STACK.push('main-menu');
    var all1 = $$('.screen');
    for (var i = 0; i < all1.length; i++) all1[i].classList.remove('active');
    var mm = document.getElementById('main-menu');
    if (mm) mm.classList.add('active');
    return;
  }
  SCREEN_STACK.pop();
  var prev = SCREEN_STACK[SCREEN_STACK.length - 1] || 'main-menu';
  var all2 = $$('.screen');
  for (var j = 0; j < all2.length; j++) all2[j].classList.remove('active');
  var next = document.getElementById(prev);
  if (next) { next.classList.add('active'); next.scrollTop = 0; }
}

document.addEventListener('click', function(e) {
  var goBtn = e.target.closest('[data-go]');
  if (goBtn) { showScreen(goBtn.dataset.go); return; }
  var backBtn = e.target.closest('[data-back]');
  if (backBtn) { goBack(); return; }
});

