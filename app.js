function handleSignup(e) {
  e.preventDefault();
  var msg = $('#signup-msg');
  msg.textContent = '';
  var username = $('#signup-user').value.trim();
  var email = $('#signup-email').value.trim().toLowerCase();
  var password = $('#signup-pass').value;

  if (username.length < 3 || username.length > 20) { msg.textContent = 'اسم المستخدم من 3 إلى 20 حرف'; return; }
  if (!/^[A-Za-z0-9_\u0600-\u06FF]+$/.test(username)) { msg.textContent = 'حروف وأرقام و _ فقط'; return; }
  if (password.length < 6) { msg.textContent = 'كلمة السر 6 حروف على الأقل'; return; }

  if (!sb) { msg.textContent = 'لا يوجد اتصال — استخدم "الدخول كزائر"'; return; }

  msg.textContent = 'جاري التحقق...';
  sb.rpc('is_username_available', { uname: username }).then(function(res) {
    if (res.error) throw res.error;
    if (!res.data) { msg.textContent = 'اسم المستخدم محجوز بالفعل'; return; }

    msg.textContent = 'جاري إنشاء الحساب...';
    return sb.auth.signUp({
      email: email,
      password: password,
      options: { data: { username: username } }
    });
  }).then(function(res) {
    if (!res) return;
    if (res.error) throw res.error;
    var data = res.data;
    if (data.user && !data.session) {
      msg.textContent = '✅ تم! افتح جيميلك لتأكيد الحساب';
      toast('تم إرسال رابط التأكيد إلى جيميلك', true);
    } else if (data.session) {
      loadProfileAndEnter(data.user);
    }
  }).catch(function(err) {
    console.error(err);
    var m = (err.message || '').toLowerCase();
    if (m.indexOf('username_taken') >= 0 || m.indexOf('duplicate') >= 0) msg.textContent = 'اسم المستخدم محجوز';
    else if (m.indexOf('already registered') >= 0) msg.textContent = 'الجيميل مسجّل بالفعل';
    else msg.textContent = 'خطأ: ' + (err.message || 'غير معروف');
  });
}

function handleLogin(e) {
  e.preventDefault();
  var msg = $('#login-msg');
  msg.textContent = '';
  var email = $('#login-email').value.trim().toLowerCase();
  var password = $('#login-pass').value;

  if (!sb) { msg.textContent = 'لا يوجد اتصال بالخادم'; return; }
  msg.textContent = 'جاري الدخول...';

  sb.auth.signInWithPassword({ email: email, password: password }).then(function(res) {
    if (res.error) throw res.error;
    loadProfileAndEnter(res.data.user);
  }).catch(function(err) {
    console.error(err);
    var m = (err.message || '').toLowerCase();
    if (m.indexOf('invalid') >= 0) msg.textContent = 'البريد أو كلمة السر خطأ';
    else if (m.indexOf('confirm') >= 0) msg.textContent = 'أكد جيميلك أولاً';
    else msg.textContent = 'خطأ: ' + (err.message || '');
  });
}

function loadProfileAndEnter(user) {
  if (!sb) return Promise.resolve();
  return sb.from('profiles').select('*').eq('id', user.id).single().then(function(res) {
    if (res.error) throw res.error;
    STATE.user = { id: user.id, email: user.email, username: res.data.username };
    STATE.profile = res.data;
    enterMainMenu();
  }).catch(function(err) {
    console.error('profile load failed:', err);
    STATE.user = { id: user.id, email: user.email, username: (user.email || '').split('@')[0] };
    enterMainMenu();
  });
}

